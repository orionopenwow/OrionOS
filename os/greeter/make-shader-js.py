#!/usr/bin/env python3
"""Wrap the shared black hole shader for the login page.

    make-shader-js.py FRAG DISK_PNG OUT_JS [LAYOUT_JSON]

The page's Content-Security-Policy allows no fetch/XHR and WebKit treats file: images as cross-origin for WebGL,
so the shader source and the painted disk go into one script file (the disk as a data: URL). os/image/art-boot.sh
runs this at install time from os/theme/blackhole/blackhole.frag (the same file the HUD and the boot frames use).
Without web/shader.js the page simply uses its 2D sky.
"""
import base64
import json
import sys


def main(argv: list[str]) -> int:
    if len(argv) < 4:
        print(__doc__.strip().splitlines()[2].strip(), file=sys.stderr)
        return 2
    frag_path, disk_path, out_path = argv[1:4]
    with open(frag_path, encoding="utf-8") as f:
        frag = f.read()
    with open(disk_path, "rb") as f:
        disk = "data:image/png;base64," + base64.b64encode(f.read()).decode()
    layout = {"wordmarkY": 0.37, "wordmarkPx": 0.062, "handoffTime": 6.0, "crop": [800, 680], "renderSize": [1280, 720]}
    if len(argv) > 4:
        try:
            with open(argv[4], encoding="utf-8") as f:
                lj = json.load(f)
            m = min(lj["renderSize"])
            layout.update(wordmarkY=lj["wordmarkY"], wordmarkPx=lj["wordmarkPx"] / m,
                          handoffTime=lj["handoff"]["u_time"], crop=lj["crop"], renderSize=lj["renderSize"])
        except (OSError, KeyError, ValueError):
            pass
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("/* generated by os/greeter/make-shader-js.py from the shared black hole shader; do not edit */\n")
        f.write("window.ORION_SHADER = " + json.dumps({"frag": frag, "disk": disk, "layout": layout}) + ";\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
