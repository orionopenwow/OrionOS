#!/usr/bin/env python3
"""Write the Orion mark as Android adaptive-icon vector drawables (foreground + themed monochrome).

    python3 os/theme/brand/android_icon.py

Geometry follows build.py's 512 grid, scaled into the 108dp adaptive canvas. The hole is nudged down-left so
the belt stays inside the 66dp safe zone.
"""
from pathlib import Path

RES = Path(__file__).resolve().parents[3] / "apps/mobile/app/src/main/res"
S = 0.17            # 512-grid units -> dp
CX, CY = 45.0, 63.0  # hole centre in dp
BELT = [(432, 82, 11.5), (385, 123, 10.5), (340, 166, 9.5)]
R = 100 * S


def circ(x, y, r):
    return f"M{x - r:.2f},{y:.2f}a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0z"


def main():
    stars = [(CX + (x - 256) * S, CY + (y - 256) * S, r * S * 1.3) for x, y, r in BELT]
    fg = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Orion mark (Art Update): the black hole with its photon ring, bright on the side turning toward you, and
     Orion's belt drifting toward its edge. Generated by os/theme/brand/android_icon.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <!-- violet halo -->
    <path android:pathData="{circ(CX, CY, 34)}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="{CX}" android:centerY="{CY}" android:gradientRadius="34">
                <item android:offset="0.45" android:color="#667C5CFF"/>
                <item android:offset="0.75" android:color="#1F7C5CFF"/>
                <item android:offset="1" android:color="#007C5CFF"/>
            </gradient>
        </aapt:attr>
    </path>
    <!-- event horizon -->
    <path android:fillColor="#000000" android:pathData="{circ(CX, CY, R - 0.9)}"/>
    <!-- faint secondary ring -->
    <path android:fillColor="#00000000" android:strokeColor="#667C5CFF" android:strokeWidth="0.5"
        android:pathData="{circ(CX, CY, R + 2.6)}"/>
    <!-- photon ring, bright on the left -->
    <path android:fillColor="#00000000" android:strokeWidth="2.0" android:pathData="{circ(CX, CY, R)}">
        <aapt:attr name="android:strokeColor">
            <gradient android:type="linear" android:startX="{CX - R:.2f}" android:startY="{CY}" android:endX="{CX + R:.2f}" android:endY="{CY}">
                <item android:offset="0" android:color="#FFF4FDFF"/>
                <item android:offset="0.22" android:color="#FF00E5FF"/>
                <item android:offset="0.62" android:color="#D97C5CFF"/>
                <item android:offset="1" android:color="#527C5CFF"/>
            </gradient>
        </aapt:attr>
    </path>
'''
    for x, y, r in stars:
        fg += f'''    <path android:fillColor="#40D8DEFF" android:pathData="{circ(x, y, r * 2.2)}"/>
    <path android:fillColor="#FFD8DEFF" android:pathData="{circ(x, y, r)}"/>
    <path android:fillColor="#FFFFFFFF" android:pathData="{circ(x, y, r * 0.55)}"/>
'''
    fg += "</vector>\n"
    (RES / "drawable/ic_launcher_foreground.xml").write_text(fg)

    mono = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Themed-icon (Android 13+) silhouette of the Orion mark: ring + belt. Generated by os/theme/brand/android_icon.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#00000000" android:strokeColor="#FF000000" android:strokeWidth="3"
        android:pathData="{circ(CX, CY, R)}"/>
'''
    for x, y, r in stars:
        mono += f'    <path android:fillColor="#FF000000" android:pathData="{circ(x, y, r * 1.3)}"/>\n'
    mono += "</vector>\n"
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(mono)
    print("wrote", RES / "drawable/ic_launcher_foreground.xml", "and ic_launcher_monochrome.xml")


if __name__ == "__main__":
    main()
