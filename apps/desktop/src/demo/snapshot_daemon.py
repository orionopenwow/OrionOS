"""Copy the real daemon's catalogues into the guest preview's sample data (apps/desktop/src/demo/sampleDaemon.json).

The GitHub Pages preview has no daemon, so its windows show these lists: the Test Center's checks, the privacy
dashboard's sensors, the project starters, the mission templates and a sample pairing QR code. Run it (or
`node scripts/update-site.mjs`) after changing any of them, so the preview never drifts from the real thing:

    python apps/desktop/src/demo/snapshot_daemon.py

Nothing personal is copied: only the built-in text of each catalogue.
"""
from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
DAEMON = HERE.parents[3] / "apps" / "daemon"
sys.path.insert(0, str(DAEMON))

import missions  # noqa: E402
import privacy_dashboard  # noqa: E402
import projects  # noqa: E402
import qr_svg  # noqa: E402
import test_center  # noqa: E402

PREVIEW_URL = "https://orionopenwow.github.io/OrionOS/#phone"


def main() -> None:
    tc = test_center.TestCenter(None, Path(tempfile.mkdtemp()), platform="orionos", profile="vm",
                                which=lambda name: "/usr/bin/" + name)
    view = tc.view()
    keep = ("id", "group", "title", "where", "kind", "detail", "next", "action", "open", "do", "watch", "by_phone")
    tests = {
        "groups": [{"id": g["id"], "title": g["title"]} for g in view["groups"]],
        "items": [{k: i[k] for k in keep} for g in view["groups"] for i in g["items"]],
    }
    sensors = [{"id": s.id, "label": s.label, "what": s.what, "how_on": s.how_on, "can_off": s.off is not None}
               for s in privacy_dashboard.PrivacyDashboard(None).sensors]
    out = {
        "_note": "Generated by snapshot_daemon.py from the daemon's own catalogues. Do not edit by hand.",
        "tests": tests,
        "privacy": sensors,
        "starters": projects.STARTERS,
        "templates": missions.TEMPLATES,
        "qr_svg": qr_svg.svg(PREVIEW_URL),
        "qr_text": PREVIEW_URL,
    }
    path = HERE / "sampleDaemon.json"
    path.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(HERE.parents[3])}: {len(tests['items'])} checks, {len(sensors)} sensors")


if __name__ == "__main__":
    main()
